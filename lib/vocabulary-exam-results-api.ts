"use client";

export interface DbVocabularyWord {
  id: number;
  word: string;
  meaningBn: string[];
  synonyms: string[];
  antonyms: string[];
  definitionEn: string;
  definitionBn: string;
  examplesEn: string[];
  examplesBn: string[];
  level: "A1" | "A2" | "B1" | "B2" | "C1" | "C2";
  category: string;
  wordType: string[];
}

export interface DbCombinedExamResult {
  id: number;
  userId: number;
  scoreInPercent: number;
  levels: string[];
  timePerWord: number;
  quizTypeId: number;
  createdAt: string | Date;
  updatedAt: string | Date;
  correctWords: DbVocabularyWord[];
  incorrectWords: DbVocabularyWord[];
  quizType?: { id: number; name: string } | null;
}

export async function fetchCombinedExamResults(): Promise<DbCombinedExamResult[]> {
  try {
    const res = await fetch("/api/v1/vocabulary-exam-result", {
      cache: "no-store",
    });
    if (!res.ok) return [];
    const body = (await res.json()) as {
      data?: DbCombinedExamResult[];
      success?: boolean;
    };
    if (!body.success || !Array.isArray(body.data)) return [];
    return body.data;
  } catch {
    return [];
  }
}

export async function fetchCombinedExamResultById(
  id: number
): Promise<DbCombinedExamResult | null> {
  try {
    const res = await fetch(`/api/v1/vocabulary-exam-result/${id}`, {
      cache: "no-store",
    });
    if (!res.ok) return null;
    const body = (await res.json()) as {
      data?: DbCombinedExamResult | null;
      success?: boolean;
    };
    if (!body.success || !body.data) return null;
    return body.data;
  } catch {
    return null;
  }
}

export function combinedExamResultDate(r: DbCombinedExamResult): string {
  const v = r.createdAt instanceof Date ? r.createdAt.toISOString() : r.createdAt;
  return v.slice(0, 10);
}

/**
 * Downloads the shareable result image (PNG) generated by
 * /api/v1/quiz/results/{id}/img for the given result. The endpoint is
 * session-protected, so this is fetched same-origin (cookies sent) and the
 * blob is saved locally as quiz-result-{id}.png.
 */
export async function downloadCombinedExamResultImage(id: number): Promise<boolean> {
  try {
    const res = await fetch(`/api/v1/quiz/results/${id}/img`, {
      cache: "no-store",
    });
    if (!res.ok) return false;
    const blob = await res.blob();
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = `quiz-result-${id}.png`;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    URL.revokeObjectURL(url);
    return true;
  } catch {
    return false;
  }
}